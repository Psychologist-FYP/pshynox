import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test.setTimeout(45000);

test('annotate synthetic turns, preserve zero versus unreviewed, confirm absence and export', async ({ page, request }) => {
  const patients = await (await request.get('/api/v1/patients')).json();
  const sessions = await (await request.get('/api/v1/sessions')).json();
  await page.goto('/workspace/research');
  await expect(page.getByRole('heading', { name: 'Retrieval evaluation', exact: true })).toBeVisible();
  await expect(page.getByLabel('Research dataset').locator('option').filter({ hasText: 'annomi · 133' })).toHaveCount(1);
  await page.getByLabel('Research dataset').selectOption('synthetic');
  await expect(page.getByRole('combobox', { name: 'Conversation', exact: true })).toHaveValue('example');
  await expect(page.getByText('Rankings are hidden here.', { exact: false })).toBeVisible();
  await page.getByLabel('Reviewer name').fill('Synthetic browser test author');
  await page.getByRole('textbox', { name: 'Query wording', exact: true }).fill('Fictional absent topic');
  await page.getByLabel('What evidence should this query retrieve?').fill('Test fixture only: check absence across both fictional turns.');
  await page.getByLabel('I reviewed and approved this query wording and intended evidence.').check();
  await page.getByRole('button', { name: 'Save query', exact: true }).click();
  await expect(page.getByText('0/2 turns reviewed', { exact: false })).toBeVisible();
  await page.locator('.research-grading').focus();
  await page.keyboard.press('0');
  await page.getByRole('textbox', { name: 'Rationale', exact: true }).fill('Synthetic fixture: unrelated to the absent topic.');
  await page.getByRole('textbox', { name: 'Rationale', exact: true }).press('Control+Enter');
  await expect(page.getByText('1/2 turns reviewed', { exact: false })).toBeVisible();
  await expect(page.locator('.research-turn').first()).toContainText('Grade 0');
  await expect(page.locator('.research-turn').nth(1)).toContainText('Unreviewed');
  await page.reload();
  await page.getByLabel('Research dataset').selectOption('synthetic');
  await expect(page.getByText('1/2 turns reviewed', { exact: false })).toBeVisible();
  await page.locator('.research-turn').nth(1).click();
  await page.getByRole('radio', { name: '0 = Irrelevant', exact: true }).check();
  await page.getByRole('textbox', { name: 'Rationale', exact: true }).fill('Synthetic fixture: this reply also lacks the topic.');
  await page.getByRole('button', { name: 'Save judgment & next' }).click();
  await expect(page.getByText('2/2 turns reviewed', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm I reviewed the full conversation: no relevant evidence' }).click();
  await expect(page.getByText('Complete for export', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Evaluation results', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export validated dataset' }).click();
  const file = await download;
  const exported = JSON.parse(await readFile((await file.path())!, 'utf8'));
  expect(exported.queries[0].no_answer_confirmed).toBe(true);
  expect(exported.judgments.map((j: { grade: number }) => j.grade)).toEqual([0, 0]);
  for (const method of ['fixture', 'tfidf', 'e5', 'hybrid']) await page.getByRole('checkbox', { name: method, exact: true }).uncheck();
  await page.getByRole('button', { name: 'Run benchmark', exact: true }).click();
  await expect(page.getByText('Run: completed', { exact: true })).toBeVisible({ timeout: 30000 });
  await expect(page.getByRole('heading', { name: 'Fictional smoke test — not dataset evaluation' })).toBeVisible();
  await page.getByRole('button', { name: 'Annotate without rankings' }).click();
  await page.locator('.research-turn').first().click();
  await page.getByRole('button', { name: 'Mark unreviewed' }).click();
  await expect(page.getByText('1/2 turns reviewed', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Evaluation results', exact: true }).click();
  await page.getByRole('button', { name: 'Export validated dataset' }).click();
  await expect(page.getByRole('alert')).toContainText('Export blocked');
  expect(await (await request.get('/api/v1/patients')).json()).toEqual(patients);
  expect(await (await request.get('/api/v1/sessions')).json()).toEqual(sessions);
});

test('existing fictional benchmark renders context, charts and missing method results', async ({ page, request }) => {
  await page.goto('/workspace/research');
  await page.getByRole('button', { name: 'Evaluation results', exact: true }).click();
  await page.getByLabel('Saved benchmark run').selectOption('fictional-smoke');
  await expect(page.getByRole('heading', { name: 'Fictional smoke test — not dataset evaluation' })).toBeVisible();
  await expect(page.getByRole('img', { name: /nDCG@10 comparison/ })).toBeVisible();
  await page.getByLabel('Evaluated query').selectOption('sleep');
  await expect(page.locator('.research-hit').first()).toContainText('Grade');
  await page.locator('.research-hit').first().getByText('Source context', { exact: true }).click();
  await expect(page.locator('.research-hit').first()).toContainText('Matched');
  const report = (await (await request.get('/api/v1/research/runs/fictional-smoke')).json()).report;
  report.results = report.results.map((r: { method: string }) => r.method === 'e5' ? { method: 'e5', variant: 'reference', status: 'unavailable', reason: 'Synthetic missing model example' } : r.method === 'hybrid' ? { method: 'hybrid', variant: 'reference', status: 'failed', reason: 'Synthetic failure example' } : r);
  await page.getByLabel('Import a benchmark results JSON').setInputFiles({ name: 'fictional-partial-report.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(report)) });
  await expect(page.locator('.research-table').first().getByRole('row').filter({ hasText: 'e5 / reference' })).toContainText('unavailable');
  const missing = page.locator('.research-table').first().getByRole('row').filter({ hasText: 'e5 / reference' });
  await expect(missing.getByRole('cell', { name: '—', exact: true })).toHaveCount(7);
  await expect(page.locator('.research-table').first().getByRole('row').filter({ hasText: 'hybrid / reference' })).toContainText('failed');
  await page.screenshot({ path: 'test-results/research-results.png', fullPage: true });
});
